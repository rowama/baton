"""2026-11-tool-steps: a recipe declares tools (§5.9; Decisions 0154, 0156, 0158).

Slice 1: a step names its tool, ``tools/<id>/tool.yaml`` is loaded and
checked with its lock file, the plan shows the tool, the recipe hash covers
the tool's files, and recipes without tools are unchanged.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from baton import versions
from baton.models import Requires
from baton.recipe import RecipeError, build_plan, load_recipe, render_plan
from baton.routing import needed_capabilities, requirement_gaps
from baton.tools import parse_lock

from conftest import ROOT, SOFTWARE_FEATURE, step

TOOL_DEMO = ROOT / "tests" / "fixtures" / "recipes" / "tool-demo"
TOOL_YAML = Path("tools") / "backtest" / "tool.yaml"
LOCK = Path("tools") / "backtest" / "requirements.lock"

# Two entries as `uv pip compile --generate-hashes` (0.13.7) writes them.
UV_LOCK = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile --generate-hashes in.txt -o out.lock
certifi==2026.10.23 \\
    --hash=sha256:a9895e6e2758b371e0545e321a3a8fd1fcfd9829ada8824a936dfb16aaaf36cd \\
    --hash=sha256:e9b54de76e530bb6cf0ccd036787103acb58fd42ba930ea8bf948ddbaa2f61d1
    # via requests
idna==3.20 ; python_version >= "3.9" \\
    --hash=sha256:01077390b03f7988f11d700a2194e69b119741a86b1a638b1db88891e3eced8e
    # via requests
"""


def _tool(edit):
    """An edit of tools/backtest/tool.yaml."""

    def apply(_: dict, d: Path) -> None:
        p = d / TOOL_YAML
        data = yaml.safe_load(p.read_text(encoding="utf-8"))
        edit(data)
        p.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")

    return apply


def _lock(text: str):
    def apply(_: dict, d: Path) -> None:
        (d / LOCK).write_text(text, encoding="utf-8")

    return apply


def _codes(make_recipe, edit) -> set[str]:
    with pytest.raises(RecipeError) as exc:
        load_recipe(make_recipe(edit, source=TOOL_DEMO))
    return exc.value.codes()


# -- a tool step loads ---------------------------------------------------------


def test_tool_step_loads_with_its_tool():
    loaded = load_recipe(TOOL_DEMO)
    node = step(loaded.recipe.model_dump(), "backtest")
    assert node["tool"] == "backtest" and node["requires"] is None and node["prompt"] is None
    tool = loaded.tools["backtest"]
    assert tool.spec.runtime.kind == "python" and tool.spec.reach.network is False
    assert tool.requirements == [] and len(tool.lock_sha256) == 64 and len(tool.sha256) == 64
    assert loaded.warnings == []


def test_plan_shows_a_tool_step_as_done_by_its_tool():
    plan = build_plan(load_recipe(TOOL_DEMO))
    rows = {r.path: r for r in plan.levels[0].steps}
    assert rows["backtest"].tool == "backtest" and rows["backtest"].requires is None
    assert rows["parameters"].tool is None
    text = render_plan(plan)
    assert "backtest    run   by tool backtest; gates: schema" in text
    assert "parameters  run   gates: schema" in text


def test_recipe_hash_covers_the_tools_files(make_recipe):
    before = load_recipe(make_recipe(source=TOOL_DEMO))
    root = before.root
    (root / "tools" / "backtest" / "backtest.py").write_text("print('changed')\n", encoding="utf-8")
    after = load_recipe(root)
    assert after.sha256 != before.sha256
    assert after.tools["backtest"].sha256 != before.tools["backtest"].sha256
    assert after.tools["backtest"].lock_sha256 == before.tools["backtest"].lock_sha256


def test_lock_with_pinned_hashed_dependencies_loads(make_recipe):
    loaded = load_recipe(make_recipe(_lock(UV_LOCK), source=TOOL_DEMO))
    reqs = loaded.tools["backtest"].requirements
    assert [(r.name, r.version, len(r.hashes)) for r in reqs] == [("certifi", "2026.10.23", 2), ("idna", "3.20", 1)]
    assert reqs[1].marker == 'python_version >= "3.9"'


def test_unused_tool_folder_is_a_warning(make_recipe):
    def edit(_: dict, d: Path) -> None:
        (d / "tools" / "spare").mkdir()

    loaded = load_recipe(make_recipe(edit, source=TOOL_DEMO))
    assert [i.code for i in loaded.warnings] == ["tool.unused"]


def test_tool_with_workspace_reach_and_secrets(make_recipe):
    def edit(r: dict, d: Path) -> None:
        step(r, "backtest")["workspace"] = "read"
        _tool(lambda t: t.update(
            reach={"workspace": "read", "network": True, "secrets": ["PRICE_FEED_TOKEN"]},
            entry=t["entry"] + ["--repo", "{workspace}"],
        ))(r, d)

    tool = load_recipe(make_recipe(edit, source=TOOL_DEMO)).tools["backtest"]
    assert tool.spec.reach.network is True and tool.spec.reach.secrets == ["PRICE_FEED_TOKEN"]


# -- a broken tool step or tool is refused with a specific error ------------------


def _set_step(key, value):
    return lambda r, _: step(r, "backtest").__setitem__(key, value)


CASES = [
    ("tool with requires", _set_step("requires", {"capabilities": ["shell"]}), "step.tool_and_worker"),
    ("tool with prompt", _set_step("prompt", "prompts/report.md"), "step.tool_and_worker"),
    ("unknown tool", _set_step("tool", "forecast"), "tool.unknown"),
    ("workspace differs from the tool's reach", _set_step("workspace", "read"), "step.tool_workspace_mismatch"),
    ("tool id not its folder", _tool(lambda t: t.update(id="other")), "tool.id_mismatch"),
    ("unsupported runtime", _tool(lambda t: t["runtime"].update(kind="node")), "tool.unknown_runtime"),
    ("bad runtime version", _tool(lambda t: t["runtime"].update(version="3.11 or newer")), "tool.bad_runtime_version"),
    ("entry runs a path", _tool(lambda t: t["entry"].__setitem__(0, "/usr/bin/python")), "tool.bad_entry_command"),
    ("entry through a shell", _tool(lambda t: t.update(entry=["sh -c", "{output}"])), "tool.bad_entry_command"),
    ("unknown placeholder", _tool(lambda t: t["entry"].append("{home}")), "tool.unknown_placeholder"),
    ("entry file missing", _tool(lambda t: t["entry"].__setitem__(1, "{tool}/missing.py")), "file.missing"),
    ("entry file outside the tool", _tool(lambda t: t["entry"].__setitem__(1, "{tool}/../../recipe.yaml")), "file.outside_recipe"),
    ("entry without output", _tool(lambda t: t.update(entry=["python", "{tool}/backtest.py"])), "tool.entry_needs_output"),
    ("workspace placeholder without reach", _tool(lambda t: t["entry"].append("{workspace}")), "tool.workspace_placeholder"),
    ("no lock file", _tool(lambda t: t["dependencies"].update(lock="missing.lock")), "file.missing"),
    ("no dependencies", _tool(lambda t: t.pop("dependencies")), "recipe.missing_key"),
    ("no description", _tool(lambda t: t.pop("description")), "recipe.missing_key"),
    ("unknown key in tool.yaml", _tool(lambda t: t.update(colour="blue")), "recipe.unknown_key"),
    ("vendor key in tool.yaml", _tool(lambda t: t.update(model="x")), "neutrality.forbidden_key"),
    ("vendor string in tool.yaml", _tool(lambda t: t.update(description="Asks gpt-4 to trade")), "neutrality.vendor_string"),
    ("bad secret name", _tool(lambda t: t["reach"].update(secrets=["price feed"])), "tool.bad_secret_name"),
    ("unpinned dependency", _lock("requests>=2.0 --hash=sha256:" + "a" * 64 + "\n"), "tool.unpinned_dependency"),
    ("dependency without hash", _lock("requests==2.32.3\n"), "tool.unhashed_dependency"),
    ("dependency with a weak hash", _lock("requests==2.32.3 --hash=md5:abc\n"), "tool.unhashed_dependency"),
    ("dependency from a URL", _lock("requests @ https://example.org/r.whl --hash=sha256:" + "a" * 64 + "\n"), "tool.unpinned_dependency"),
    ("option in the lock", _lock("--index-url https://example.org/simple\n"), "tool.lock_option"),
    ("editable in the lock", _lock("-e ./src\n"), "tool.lock_option"),
]


@pytest.mark.parametrize("name,edit,code", CASES, ids=[c[0] for c in CASES])
def test_broken_tool_rejected(make_recipe, name, edit, code):
    assert code in _codes(make_recipe, edit)


def test_lock_errors_name_the_line(make_recipe):
    with pytest.raises(RecipeError) as exc:
        load_recipe(make_recipe(_lock("# pinned\n\nrequests==2.32.3\n"), source=TOOL_DEMO))
    (issue,) = [i for i in exc.value.issues if i.code == "tool.unhashed_dependency"]
    assert issue.where == "tools/backtest/requirements.lock:3"


def test_worker_step_still_needs_requires_and_prompt(make_recipe):
    def edit(r: dict, _: Path) -> None:
        del step(r, "plan")["requires"]
        del step(r, "design")["prompt"]

    with pytest.raises(RecipeError) as exc:
        load_recipe(make_recipe(edit))
    missing = {i.where for i in exc.value.issues if i.code == "recipe.missing_key"}
    assert {"plan.requires", "design.prompt"} <= missing


# -- nothing changes for recipes without tools ------------------------------------


def test_recipe_without_tools_is_unchanged():
    loaded = load_recipe(SOFTWARE_FEATURE)
    assert loaded.tools == {}
    assert all("tool" not in v for v in versions.step_signatures(loaded).values())
    sig = versions.step_signatures(load_recipe(TOOL_DEMO))["backtest"]
    assert sig["tool"] == "backtest" and sig["capabilities"] == []
    assert all(r.tool is None for lv in build_plan(loaded).levels for r in lv.steps)


def test_no_worker_can_do_a_tool_step(make_recipe):
    loaded = load_recipe(TOOL_DEMO)
    assert needed_capabilities(None, "none") == []
    assert requirement_gaps(None, "none", None, loaded.vocab) == ["this step is done by its tool, not by a worker (§5.9)"]  # type: ignore[arg-type]
    assert needed_capabilities(Requires(capabilities=["shell"]), "none") == ["shell"]


# -- the lock parser --------------------------------------------------------------


def test_parse_lock_reads_uv_output():
    reqs, problems = parse_lock(UV_LOCK)
    assert problems == []
    assert [r.name for r in reqs] == ["certifi", "idna"]


def test_parse_lock_extras_and_empty():
    assert parse_lock("") == ([], [])
    reqs, problems = parse_lock("uvicorn[standard]==0.30.1 --hash=sha256:" + "b" * 64 + "\n")
    assert problems == [] and reqs[0].name == "uvicorn" and reqs[0].version == "0.30.1"
    _, problems = parse_lock("x===1.0 --hash=sha256:" + "c" * 64 + "\n")
    assert [p.code for p in problems] == ["tool.unpinned_dependency"]


def test_tool_recipe_conforms_to_published_schema():
    import json

    from jsonschema import Draft202012Validator

    from baton.data import path as data_path

    schema = json.loads((data_path("formats") / "baton-recipe-1.schema.json").read_text(encoding="utf-8"))
    raw = yaml.safe_load((TOOL_DEMO / "recipe.yaml").read_text(encoding="utf-8"))
    assert not [e.message for e in Draft202012Validator(schema).iter_errors(raw)]


def test_a_tool_step_may_raise_its_attempts(make_recipe):
    assert load_recipe(make_recipe(_set_step("max_attempts", 3), source=TOOL_DEMO)).recipe.steps[1].max_attempts == 3


def test_max_attempts_is_for_tool_steps_only(make_recipe):
    with pytest.raises(RecipeError) as exc:
        load_recipe(make_recipe(lambda r, _: step(r, "parameters").__setitem__("max_attempts", 2), source=TOOL_DEMO))
    assert exc.value.codes() == {"step.max_attempts_needs_tool"}


def test_a_tool_step_may_have_review_and_human_gates(make_recipe):
    def edit(r: dict, d: Path) -> None:
        (d / "prompts" / "rubric.md").write_text("Are the trades plausible?", encoding="utf-8")
        step(r, "backtest")["gates"] += [
            {"type": "review", "reviewer_requires": {"capabilities": ["structured_output"]}, "rubric": "prompts/rubric.md",
             "block_on": ["critical"], "independence": {"from_step": "backtest", "level": "different_vendor"}},
            {"type": "human", "prompt": "Accept these results?"},
        ]

    loaded = load_recipe(make_recipe(edit, source=TOOL_DEMO))
    assert [g.type for g in loaded.recipe.steps[1].gates] == ["schema", "review", "human"]
